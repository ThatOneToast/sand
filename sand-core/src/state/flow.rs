    fn push_hook(
        &mut self,
        kind: FlowHookPhase,
        state: S,
        cadence: u32,
        commands: impl IntoCommands,
    ) {
        let hook = FlowHook {
            kind,
            state: state.to_score(),
            commands: commands.into_commands(),
            cadence,
            order: self.next_order,
        };
        self.next_order += 1;
        if !self.hooks.iter().any(|existing| {
            existing.kind == hook.kind
                && existing.state == hook.state
                && existing.commands.identity() == hook.commands.identity()
                && existing.cadence == hook.cadence
        }) {
            self.hooks.push(hook);
        }
    }

