#[derive(Debug, Clone, PartialEq)]
pub(crate) struct FlowTransition {
    pub(crate) from: i32,
    pub(crate) to: i32,
    pub(crate) guard: Option<Condition>,
    pub(crate) priority: i32,
    pub(crate) order: usize,
}

#[derive(Debug, Clone)]
pub(crate) struct FlowHook {
    pub(crate) kind: FlowHookPhase,
    pub(crate) state: i32,
    pub(crate) commands: Actions,
    pub(crate) cadence: u32,
    pub(crate) order: usize,
}

impl PartialEq for FlowHook {
    fn eq(&self, other: &Self) -> bool {
        self.kind == other.kind
            && self.state == other.state
            && self.cadence == other.cadence
            && self.order == other.order
            && self.commands.identity() == other.commands.identity()
    }
}

impl FlowTransition {
    fn guard_plans(&self) -> Vec<Vec<String>> {
        self.guard
            .as_ref()
            .map_or_else(|| vec![Vec::new()], |guard| guard.rendered_plans(false))
    }
}

