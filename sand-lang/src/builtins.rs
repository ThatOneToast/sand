//! The built-in vocabulary of the Sand language, with its documentation.
//!
//! One table drives argument checking in analysis and the explanations shown
//! by hover and completion, so documentation cannot drift from behaviour.

/// How a builtin is written.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuiltinKind {
    /// A statement call: `play_sound("...");`.
    Statement,
    /// A macro taking a format string: `chat!("...");`.
    Macro,
    /// An expression: `random(1..=6)`.
    Expression,
    /// A predicate in a condition: `if has_state(Mana) { ... }`.
    Condition,
}

/// What an argument accepts.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ParamKind {
    /// A typed vanilla registry value such as `Item::Diamond`, named by its
    /// registry. A namespaced string is accepted for modded or custom values.
    Registry(&'static str),
    /// A text format string with `{...}` interpolation.
    Format,
    /// A plain string.
    Text,
    /// A whole number; individual builtins document whether runtime values are accepted.
    Int,
    /// A decimal or integer; individual builtins document whether runtime values are accepted.
    Number,
    /// `true` or `false`.
    Bool,
    /// A function name.
    Function,
    /// A constant range such as `1..=6`.
    Range,
    /// A declared `entity state`.
    EntityState,
    /// A scoreboard-backed number field on player or entity State.
    QueryScore,
    /// A compile-time typed Minecraft NBT compound.
    NbtCompound,
    /// A `timer` State field, written `State.field`.
    Timer,
    /// A block position: `pos(x, y, z)` or `offset(dx, dy, dz)`.
    Position,
    /// A declared `bossbar`.
    BossBar,
    /// A declared or external native predicate resource.
    Predicate,
    /// A declared or external native advancement.
    Advancement,
    /// A declared or external native dialog.
    Dialog,
    /// A declared or external native structure template.
    StructureTemplate,
    /// An authored inventory transfer definition.
    InventoryTransfer,
    /// An authored player-owned HUD.
    Hud,
    /// An authored player-owned dialog menu.
    Menu,
    /// An authored player-owned projectile.
    Projectile,
    /// An authored progression track.
    Progression,
    /// An authored native display scene.
    Scene,
    /// An authored bounded job.
    Job,
    /// An authored session controller.
    Session,
    /// A checked player activation.
    Ability,
    /// An authored custom health policy.
    Combat,
    /// A declared `loot` table.
    Loot,
    /// A retained EntityRef value.
    EntityRef,
    /// A value of the receiver collection's element type.
    Value,
}

/// One builtin parameter.
#[derive(Debug, Clone, Copy)]
pub struct Param {
    /// Parameter name, usable as `name = value`.
    pub name: &'static str,
    /// Accepted value.
    pub kind: ParamKind,
    /// Whether the argument must be supplied.
    pub required: bool,
    /// Explanation shown in hover.
    pub doc: &'static str,
}

/// One builtin statement, macro, or expression.
#[derive(Debug, Clone, Copy)]
pub struct Builtin {
    /// Source name, without `!` for macros.
    pub name: &'static str,
    /// How it is written.
    pub kind: BuiltinKind,
    /// Signature shown in hover and completion.
    pub signature: &'static str,
    /// One-line summary.
    pub summary: &'static str,
    /// Longer explanation.
    pub details: &'static str,
    /// The Minecraft command it becomes.
    pub minecraft: &'static str,
    /// Whether it needs a player executor.
    pub needs_player: bool,
    /// Parameters in positional order.
    pub params: &'static [Param],
    /// Completion snippet.
    pub snippet: &'static str,
}

const fn p(name: &'static str, kind: ParamKind, required: bool, doc: &'static str) -> Param {
    Param {
        name,
        kind,
        required,
        doc,
    }
}

