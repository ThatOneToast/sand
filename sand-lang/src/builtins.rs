/// What a data-declaration field accepts.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FieldKind {
    /// A vanilla item (`Item::Diamond`) or a declared custom item.
    Item,
    /// A recipe ingredient: a vanilla item, an item `tag`, or `"#ns:tag"`.
    Ingredient,
    /// A list of ingredients.
    Ingredients,
    /// Text with style interpolation, such as `"{red}Ruby Sword"`.
    Text,
    /// Stable criterion names mapped to typed advancement triggers.
    AdvancementCriteria,
    /// Icon, title, description and background for an advancement.
    AdvancementDisplay,
    /// The author, title and pages of a written book.
    WrittenBook,
    /// A quoted RGB color such as `"#3f76e4"`.
    Color,
    /// Ordered block and height pairs for a flat dimension.
    FlatLayers,
    /// A quoted namespaced resource location.
    ResourceId,
    /// A quoted path to a binary asset relative to the package root.
    AssetPath,
    /// Parameterless function that runs after a native operation.
    Callback,
    /// A named function with one numeric index and no return value.
    JobStep,
    SceneParts,
    SceneKeyframes,
    /// Title, progress and maximum for a private HUD bar.
    HudBossBar,
    /// An ordered list of rich button labels and their callbacks.
    MenuChoices,
    MenuViews,
    BooleanState,
    MenuViewName,
    BiomeSpawners,
    ProgressionObjectives,
    ProgressionBranches,
    ProgressionRef,
    AbilityCost,
    CombatCritical,
    StateCooldown,
    ProjectileRef,
    PlayerStateNumber,
    BiomeSpawnCosts,
    /// A list of text lines.
    TextList,
    /// A shaped pattern: a list of one to three strings.
    Pattern,
    /// `{ X: ingredient, ... }` for a shaped pattern.
    Key,
    /// `true` or `false`.
    Bool,
    /// A whole number; individual builtins document whether runtime values are accepted.
    Int,
    /// A decimal or integer; individual builtins document whether runtime values are accepted.
    Number,
    /// A value from a typed set, such as `Rarity::Epic`.
    Registry(&'static str),
    /// A list of typed enchantment and level pairs.
    Enchantments,
    /// A list of tag values for the declaration's registry.
    TagValues,
    /// A list of loot choices.
    LootItems,
}

/// One documented field of a data declaration.
#[derive(Debug, Clone, Copy)]
pub struct DataFieldDoc {
    /// Declaration keyword: `item`, `recipe`, item `tag`, ...
    pub kind: &'static str,
    /// Field name.
    pub name: &'static str,
    /// Accepted value.
    pub value: FieldKind,
    /// Whether the field must be present (recipe kinds are checked separately).
    pub required: bool,
    /// Explanation for hover and completion.
    pub doc: &'static str,
    /// Completion snippet for the value.
    pub snippet: &'static str,
}

const fn f(
    kind: &'static str,
    name: &'static str,
    value: FieldKind,
    required: bool,
    doc: &'static str,
    snippet: &'static str,
) -> DataFieldDoc {
    DataFieldDoc {
        kind,
        name,
        value,
        required,
        doc,
        snippet,
    }
}

/// The recipe fields that choose the recipe type; exactly one is required.
pub const RECIPE_TYPES: &[&str] = &[
    "shaped",
    "shapeless",
    "smelting",
    "blasting",
    "smoking",
    "campfire",
    "stonecutting",
    "smithing",
    "smithing_trim",
];

/// Whether a recipe type accepts a field, shared by validation and completion.
pub fn recipe_accepts_field(kind: Option<&str>, field: &str) -> bool {
    match field {
        name if RECIPE_TYPES.contains(&name) => kind.is_none(),
        "key" => kind == Some("shaped"),
        "base" | "addition" => matches!(kind, Some("smithing" | "smithing_trim")),
        "trim_pattern" => kind == Some("smithing_trim"),
        "result" | "count" => kind != Some("smithing_trim"),
        "experience" | "time" => {
            matches!(kind, Some("smelting" | "blasting" | "smoking" | "campfire"))
        }
        _ => true,
    }
}

