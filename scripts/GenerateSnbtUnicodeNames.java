/** Regenerates selector/java_names.rs with Java 25's Unicode 16 name exceptions.
 * Run: java scripts/GenerateSnbtUnicodeNames.java > sand-commands/src/selector/java_names.rs
 * Standard Unicode names are supplied by unicode_names2; Java uses historical
 * control names and block-based names for several algorithmic Unicode ranges.
 */
class GenerateSnbtUnicodeNames {
    public static void main(String[] args) {
        if (Runtime.version().feature() != 25) {
            throw new IllegalStateException("Use Java 25 to match Minecraft 26's Unicode 16 baseline");
        }
        System.out.println("// Generated by scripts/GenerateSnbtUnicodeNames.java using Java 25; do not edit.");
        System.out.println("pub(super) const CONTROL_NAMES: &[&str] = &[");
        for (int point = 0; point <= 0x9f; point++) {
            if (Character.isISOControl(point)) {
                System.out.printf("    \"%s\",%n", Character.getName(point));
            }
        }
        System.out.println("];\npub(super) const BLOCK_NAMES: &[(&str, u32, u32)] = &[");
        String previous = null;
        int start = 0;
        for (int point = 0; point <= Character.MAX_CODE_POINT + 1; point++) {
            String prefix = null;
            if (point <= Character.MAX_CODE_POINT) {
                var block = Character.UnicodeBlock.of(point);
                if (block != null) {
                    var candidate = block.toString().replace('_', ' ');
                    if ((candidate + " " + Integer.toHexString(point).toUpperCase(java.util.Locale.ROOT))
                            .equals(Character.getName(point))) {
                        prefix = candidate;
                    }
                }
            }
            if (!java.util.Objects.equals(previous, prefix)) {
                if (previous != null) {
                    System.out.printf("    (\"%s\", 0x%X, 0x%X),%n", previous, start, point - 1);
                }
                previous = prefix;
                start = point;
            }
        }
        System.out.println("];");
    }
}
